BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_catalog.pg_class AS c
        JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public'
          AND c.relkind IN ('r', 'p', 'v', 'm', 'f', 'S')
    ) THEN
        RAISE EXCEPTION 'La base % ya contiene tablas, vistas o secuencias en public. Selecciona una base vacia dedicada a la app; usa las migraciones Django para actualizar una instalacion existente.', current_database();
