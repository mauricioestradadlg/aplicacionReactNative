"""Genera la instalación PostgreSQL actual sin leer .env ni conectarse a bases."""
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'backend/servidor'))

from django.conf import settings

settings.configure(
    INSTALLED_APPS=['movil'],
    DATABASES={'default': {'ENGINE': 'django.db.backends.postgresql', 'NAME': 'schema_export_only'}},
    DEFAULT_AUTO_FIELD='django.db.models.BigAutoField',
    USE_TZ=True,
)

import django
django.setup()

from django.db import connections
from django.db.migrations.loader import MigrationLoader

loader = MigrationLoader(None)
leaves = loader.graph.leaf_nodes('movil')
state = loader.project_state(leaves)
connection = connections['default']
# PostgreSQL 15 es el mínimo de Django 6.1. La exportación no abre conexiones.
connection.__dict__['pg_version'] = 150000
with connection.schema_editor(collect_sql=True, atomic=False) as editor:
    for model in state.apps.get_app_config('movil').get_models():
        editor.create_model(model)
sql = '\n'.join(editor.collected_sql)
names = sorted({name for leaf in leaves for app, name in loader.graph.forwards_plan(leaf) if app == 'movil'})
markers = '\n'.join(
    f"INSERT INTO django_migrations (app, name, applied) VALUES ('movil', '{name}', CURRENT_TIMESTAMP);"
    for name in names
)
header = '''-- ESQUEMA ACTUAL DE LA APLICACION MOVIL PARA POSTGRESQL / NEON
-- Solo para una base vacia dedicada a la app; nunca sobre una instalacion existente.
-- Generado con scripts/exportar-esquema-movil.py desde el estado final de migraciones.
-- Las ventas se cobran en su totalidad por monto_venta y fecha_venta.
-- No incluye usuarios, credenciales ni datos de ejemplo.
-- Para actualizar una base existente usa: manage.py migrate movil --database=movil.
BEGIN;
SET LOCAL search_path TO public;
DO $verificar_destino$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_catalog.pg_class AS c
        JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'v', 'm', 'f', 'S')
    ) THEN
        RAISE EXCEPTION 'La base contiene tablas, vistas o secuencias. Usa las migraciones Django para actualizarla.';
    END IF;
END;
$verificar_destino$;
'''
footer = '''
CREATE TABLE django_migrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app varchar(255) NOT NULL,
    name varchar(255) NOT NULL,
    applied timestamp with time zone NOT NULL
);
'''
destination = root / 'backend/sql/02_esquema_aplicacion.sql'
destination.write_text(header + sql + '\n' + footer + markers + '\nCOMMIT;\n', encoding='utf-8', newline='\n')
print('Esquema actual exportado sin conexión: ' + ', '.join(names))
